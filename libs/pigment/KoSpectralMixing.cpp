float KoSpectralMixing::uncompandSrgb(float x)
{
    return x > 0.04045f ? powf((x + 0.055f) / 1.055f, 2.4f) : x / 12.92f;
}

float KoSpectralMixing::compandSrgb(float x)
{
    return x > 0.0031308f ? 1.055f * powf(x, 1.0f / 2.4f) - 0.055f : x * 12.92f;
}

void KoSpectralMixing::lrgbToReflectance(float r, float g, float b, float reflectance[SampleCount])
{
    r = clamp01(r);
    g = clamp01(g);
    b = clamp01(b);

    const float w = qMin(r, qMin(g, b));
    r -= w;
    g -= w;
    b -= w;

    const float c = qMin(g, b);
    const float m = qMin(r, b);
    const float y = qMin(r, g);
    const float rr = qMax(0.0f, qMin(r - b, r - g));
    const float gg = qMax(0.0f, qMin(g - b, g - r));
    const float bb = qMax(0.0f, qMin(b - g, b - r));

    const float eps = 1e-7f;
    for (int i = 0; i < SampleCount; ++i) {
        const float v = w * baseSpectra[0][i] + c * baseSpectra[1][i] + m * baseSpectra[2][i] + y * baseSpectra[3][i]
            + rr * baseSpectra[4][i] + gg * baseSpectra[5][i] + bb * baseSpectra[6][i];
        reflectance[i] = qMax(eps, v);
    }
}

void KoSpectralMixing::reflectanceToLrgb(const float reflectance[SampleCount], float rgb[3])
{
    float xyz[3] = {0.0f, 0.0f, 0.0f};
    for (int i = 0; i < SampleCount; ++i) {
        xyz[0] += cmf[0][i] * reflectance[i];
        xyz[1] += cmf[1][i] * reflectance[i];
        xyz[2] += cmf[2][i] * reflectance[i];
    }

    for (int c = 0; c < 3; ++c) {
        rgb[c] = clamp01(xyzToLrgb[c][0] * xyz[0] + xyzToLrgb[c][1] * xyz[1] + xyzToLrgb[c][2] * xyz[2]);
    }
}

float KoSpectralMixing::luminance(const float reflectance[SampleCount])
{
    float y = 0.0f;
    for (int i = 0; i < SampleCount; ++i) {
        y += cmf[1][i] * reflectance[i];
    }
    return qMax(1e-7f, y);
}

void KoSpectralMixing::mix(const float dstR[SampleCount],
                           float dstFactor,
                           const float srcR[SampleCount],
                           float srcFactor,
                           float outR[SampleCount])
{
    const float dstConcentration = dstFactor * dstFactor * luminance(dstR);
    const float srcConcentration = srcFactor * srcFactor * luminance(srcR);
    const float total = dstConcentration + srcConcentration;

    if (total <= 0.0f) {
        for (int i = 0; i < SampleCount; ++i) {
            outR[i] = dstR[i];
        }
        return;
    }

    for (int i = 0; i < SampleCount; ++i) {
        const float ksMix =
            (reflectanceToKs(dstR[i]) * dstConcentration + reflectanceToKs(srcR[i]) * srcConcentration) / total;
        outR[i] = ksToReflectance(ksMix);
    }
}

void KoSpectralMixing::mixLrgb(const float dstLrgb[3],
                               const float srcLrgb[3],
                               float dstFactor,
                               float srcFactor,
                               float outLrgb[3])
{
    float dstR[SampleCount];
    float srcR[SampleCount];
    float outR[SampleCount];

    lrgbToReflectance(dstLrgb[0], dstLrgb[1], dstLrgb[2], dstR);
    lrgbToReflectance(srcLrgb[0], srcLrgb[1], srcLrgb[2], srcR);
    mix(dstR, dstFactor, srcR, srcFactor, outR);
    reflectanceToLrgb(outR, outLrgb);
}
